from typing import Dict, Any


def should_take_trade(expected_payoff_ratio: float, win_probability: float, min_expectancy_ratio: float = 0.20) -> bool:
    """
    基于概率决策树判断交易是否值得执行:
    期望效用得分 = p * b - (1 - p)
    若期望效用 >= min_expectancy_ratio，则批准执行，否则放弃
    
    :param expected_payoff_ratio: 预期盈亏比 b (例如 2.5 表示预期平均盈利是止损额的 2.5 倍)
    :param win_probability: 预期胜率 p (0.0 ~ 1.0)
    :param min_expectancy_ratio: 最低期望效用门槛 (默认 0.20 R)
    :return: True 批准执行，False 拒绝放弃
    """
    score = win_probability * expected_payoff_ratio - (1.0 - win_probability)
    return score >= min_expectancy_ratio


def calculate_kelly_fraction(expected_payoff_ratio: float, win_probability: float, half_kelly: bool = True) -> float:
    """
    计算凯利最优资金仓位下注比例:
    f* = (p * b - (1 - p)) / b
    
    :param expected_payoff_ratio: 盈亏比 b
    :param win_probability: 胜率 p
    :param half_kelly: 是否采用稳健半凯利 (0.5 * f*)
    :return: 下注资金占比 (0.0 ~ 1.0)
    """
    if expected_payoff_ratio <= 0.0:
        return 0.0
    f_star = (win_probability * expected_payoff_ratio - (1.0 - win_probability)) / expected_payoff_ratio
    if f_star <= 0.0:
        return 0.0
    f_res = 0.5 * f_star if half_kelly else f_star
    return round(min(f_res, 1.0), 4)


if __name__ == "__main__":
    # 基础决策树断言
    assert should_take_trade(2.5, 0.40) == True # 0.4 * 2.5 - 0.6 = 1.0 - 0.6 = 0.4 >= 0.20
    assert should_take_trade(1.5, 0.40) == False # 0.4 * 1.5 - 0.6 = 0.6 - 0.6 = 0.0 < 0.20

    # 凯利公式辅助计算测试
    # p = 0.5, b = 2.0 -> f* = (0.5*2 - 0.5)/2 = 0.5/2 = 0.25 -> half kelly = 0.1250
    k_half = calculate_kelly_fraction(2.0, 0.5, half_kelly=True)
    assert k_half == 0.1250

